# frozen_string_literal: true

module SpecGen
  module Generators
    module Report
      # Раздел 1, второй подраздел: прогон собранного класса на его же
      # фикстурах.
      #
      # Устроен так же, как сверка со спецификацией, и стоит рядом с ней
      # намеренно: первая отвечает, правильной ли формы то, что собрано,
      # вторая — работает ли оно. Виды находок другие (синтезированного тела у
      # вызова не бывает), поэтому свой порядок и свои тексты.
      class Run < Checks
        # Синтезированных находок у прогона нет: вызов либо сошёлся с
        # фикстурой, либо нет, либо его нечем было сделать.
        ORDER = %i[failed unchecked].freeze
        PREFIX = 'run'
      end
    end
  end
end
